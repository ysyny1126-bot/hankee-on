export const KEEP_DATA: Record<string, KeepData> = {};

/** 분류(category)를 받아 상한 신호 기본값을 채운다. */
export function buildKeepData(categories: Record<string, string>) {
  for (const [name, [fridge, freezer, room, tip, signs]] of Object.entries(ROWS)) {
    KEEP_DATA[name] = {
      fridge: fridge || undefined,
      freezer: freezer || undefined,
      room: room || undefined,
      tip,
      signs: signs ?? SIGNS[categories[name]] ?? SIGNS.양념,
    };
  }
}

/** 한 줄 요약(재료 목록 등 좁은 자리용) */
export function keepLine(k: KeepData): string {
  const parts = [k.fridge && `냉장 ${k.fridge}`, k.freezer && `냉동 ${k.freezer}`, k.room && `실온 ${k.room}`].filter(Boolean);
  return [parts.join(' · '), k.tip].filter(Boolean).join(' — ');
}
